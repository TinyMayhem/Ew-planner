export function translateR4Text(value,language='es'){
 if(language!=='es')return String(value??'');
 const text=String(value??''),trim=text.trim();
 if(!trim)return text;
 const translated=ES[trim]||patterns.reduce((cur,[re,replacement])=>cur===trim&&re.test(trim)?trim.replace(re,replacement):cur,trim);
 return text.replace(trim,translated);
}
